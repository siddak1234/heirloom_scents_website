/**
 * Scans public/images and emits a typed manifest with real dimensions, so every
 * next/image gets explicit width/height and the site ships zero layout shift.
 * Run after replacing any placeholder: npm run extract:design
 */
import sharp from "sharp";
import { readdir, writeFile } from "node:fs/promises";

const GROUPS = ["brand", "scents", "photos"];
const entries = [];

for (const group of GROUPS) {
  const dir = `public/images/${group}`;
  for (const file of (await readdir(dir)).sort()) {
    if (!/\.(png|jpe?g|webp|avif)$/i.test(file)) continue;
    const { width, height } = await sharp(`${dir}/${file}`).metadata();
    if (!width || !height) throw new Error(`No dimensions for ${dir}/${file}`);
    const key = file.replace(/\.[^.]+$/, "");
    entries.push({ key, src: `/images/${group}/${file}`, width, height });
  }
}

const body = entries
  .map(
    (e) =>
      `  "${e.key}": { src: "${e.src}", width: ${String(e.width)}, height: ${String(e.height)} },`,
  )
  .join("\n");

await writeFile(
  "src/content/image-manifest.ts",
  `// GENERATED by scripts/build-image-manifest.mjs — do not edit by hand.
// Run \`npm run extract:design\` after replacing any image.

export interface ImageAsset {
  readonly src: string;
  readonly width: number;
  readonly height: number;
}

export const IMAGES = {
${body}
} as const satisfies Record<string, ImageAsset>;

export type ImageKey = keyof typeof IMAGES;

export function image(key: ImageKey): ImageAsset {
  return IMAGES[key];
}
`,
);
console.log(`manifest written: ${String(entries.length)} images`);
