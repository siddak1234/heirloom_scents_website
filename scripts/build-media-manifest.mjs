/**
 * Scans public/images and public/video and emits a typed manifest with real
 * dimensions, so every next/image and every <video> gets explicit width and
 * height and the site ships zero layout shift.
 *
 * Run after adding or replacing any asset: npm run media:manifest
 *
 * Video dimensions come from each reel's poster frame rather than from the
 * container, which keeps this script free of an ffprobe dependency — the
 * posters are generated at the video's own resolution, so the two agree.
 */
import sharp from "sharp";
import { readdir, writeFile } from "node:fs/promises";

const IMAGE_GROUPS = ["brand", "scents", "photos"];
const VIDEO_DIR = "public/video";

const images = [];
for (const group of IMAGE_GROUPS) {
  const dir = `public/images/${group}`;
  for (const file of (await readdir(dir)).sort()) {
    if (!/\.(png|jpe?g|webp|avif)$/i.test(file)) continue;
    const { width, height } = await sharp(`${dir}/${file}`).metadata();
    if (!width || !height) throw new Error(`No dimensions for ${dir}/${file}`);
    images.push({
      key: file.replace(/\.[^.]+$/, ""),
      src: `/images/${group}/${file}`,
      width,
      height,
    });
  }
}

const videos = [];
for (const file of (await readdir(VIDEO_DIR)).sort()) {
  if (!file.endsWith(".mp4")) continue;
  const key = file.replace(/\.mp4$/, "");
  const poster = `${key}-poster.jpg`;
  const { width, height } = await sharp(`${VIDEO_DIR}/${poster}`).metadata();
  if (!width || !height) throw new Error(`No poster dimensions for ${VIDEO_DIR}/${poster}`);
  videos.push({ key, src: `/video/${file}`, poster: `/video/${poster}`, width, height });
}

const imageBody = images
  .map(
    (e) =>
      `  "${e.key}": { src: "${e.src}", width: ${String(e.width)}, height: ${String(e.height)} },`,
  )
  .join("\n");

const videoBody = videos
  .map(
    (e) =>
      `  "${e.key}": { src: "${e.src}", poster: "${e.poster}", width: ${String(e.width)}, height: ${String(e.height)} },`,
  )
  .join("\n");

await writeFile(
  "src/content/media-manifest.ts",
  `// GENERATED by scripts/build-media-manifest.mjs — do not edit by hand.
// Run \`npm run media:manifest\` after adding or replacing any asset.

export interface ImageAsset {
  readonly src: string;
  readonly width: number;
  readonly height: number;
}

export interface VideoAsset extends ImageAsset {
  /** Frame shown before playback, and the still that reduced motion keeps. */
  readonly poster: string;
}

export const IMAGES = {
${imageBody}
} as const satisfies Record<string, ImageAsset>;

export const VIDEOS = {
${videoBody}
} as const satisfies Record<string, VideoAsset>;

export type ImageKey = keyof typeof IMAGES;
export type VideoKey = keyof typeof VIDEOS;

export function image(key: ImageKey): ImageAsset {
  return IMAGES[key];
}

export function video(key: VideoKey): VideoAsset {
  return VIDEOS[key];
}
`,
);
console.log(`manifest written: ${String(images.length)} images, ${String(videos.length)} videos`);
